function decode(s) {
  return s
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&#39;|&rsquo;|&lsquo;|&apos;/g, "'")
    .replace(/&quot;|&ldquo;|&rdquo;/g, '"')
    .replace(/&nbsp;/g, " ").replace(/&[a-z]+;/gi, " ")
    .replace(/\s+/g, " ").trim();
}
function clean(html) {
  return decode(String(html || "").replace(/<[^>]+>/g, " "));
}
const NOISE = /^(welcome|explorer|back to|home|menu|subscribe|newsletter|follow|copyright|share|download|read more|view all|next|previous|loading|toggle|click|search|sarit classes)\b/i;

async function extract(slug, page) {
  const res = await fetch(BASE + page, { headers: { "User-Agent": "Mozilla/5.0" } });
  let html = await res.text();
  const title = clean((html.match(/<title>([^<]*)<\/title>/i) || [])[1] || slug);
  html = html.replace(/<script[\s\S]*?<\/script>/gi, "").replace(/<style[\s\S]*?<\/style>/gi, "");

  const re = /<(h[1-4]|summary|li)\b[^>]*>([\s\S]*?)<\/\1>/gi;
  let m;
  const papers = [];
  let curPaper = null;
  let curSection = null;
  const setPaper = (label) => {
    curPaper = papers.find((p) => p.paper === label);
    if (!curPaper) { curPaper = { paper: label, sections: [] }; papers.push(curPaper); }
    curSection = null;
  };
  const paperLabel = (text) => {
    const mm = text.match(/^\s*paper\s*[-:–]?\s*(i{1,2}|1|2|one|two)\b/i);
    if (!mm) return null;
    const t = mm[1].toLowerCase();
    return (t === "ii" || t === "2" || t === "two") ? "Paper II" : "Paper I";
  };
  const addTopic = (text) => {
    if (!curPaper) setPaper("Paper I");
    if (!curSection) { curSection = { heading: "Topics", topics: [] }; curPaper.sections.push(curSection); }
    if (!curSection.topics.includes(text)) curSection.topics.push(text);
  };

  while ((m = re.exec(html))) {
    const tag = m[1].toLowerCase();
    const text = clean(m[2]);
    if (!text || text.length < 2 || text.length > 200) continue;
    const isHeading = tag === "h1" || tag === "h2" || tag === "h3" || tag === "summary";
    if (isHeading && NOISE.test(text)) continue;
    const pl = isHeading ? paperLabel(text) : null;
    if (pl) { setPaper(pl); continue; }
    if (isHeading) {
      if (!curPaper) setPaper("Paper I");
      curSection = { heading: text, topics: [] };
      curPaper.sections.push(curSection);
    } else {
      addTopic(text); // h4 or li -> topic
    }
  }
  papers.forEach((p) => { p.sections = p.sections.filter((s) => s.topics.length > 0); });
  return { slug, title, sourceUrl: BASE + page, papers: papers.filter((p) => p.sections.length > 0) };
}


const out = {};
for (const [slug, page] of Object.entries(PAGES)) {
  try {
    const data = await extract(slug, page);
    const topicCount = data.papers.reduce((n, p) => n + p.sections.reduce((s, sec) => s + sec.topics.length, 0), 0);
    out[slug] = data;
    console.error(`ok   ${slug}: ${data.papers.length} paper(s), ${topicCount} topics`);
  } catch (e) {
    console.error(`FAIL ${slug}: ${e.message}`);
  }
}
mkdirSync("src/lib/upsc/generated", { recursive: true });
const header =
  "// AUTO-GENERATED by scripts/build-optional-content.mjs from saritclasses.com. Do not edit by hand.\n" +
  "export type OptionalTopicSection = { heading: string; topics: string[] };\n" +
  "export type OptionalPaperContent = { paper: string; sections: OptionalTopicSection[] };\n" +
  "export type OptionalSubjectContent = { slug: string; title: string; sourceUrl: string; papers: OptionalPaperContent[] };\n" +
  "export const optionalSubjectsContent: Record<string, OptionalSubjectContent> = ";
writeFileSync(
  "src/lib/upsc/generated/optionalSubjectsContent.ts",
  header + JSON.stringify(out, null, 2) + ";\n"
);
