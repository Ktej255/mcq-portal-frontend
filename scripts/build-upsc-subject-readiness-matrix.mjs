import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function readSource(relativePath) {
  return readFile(path.join(root, relativePath), "utf8");
}

function extractDelimited(source, marker, openCharacter, closeCharacter) {
  const markerIndex = source.indexOf(marker);
  if (markerIndex === -1) throw new Error(`Missing marker: ${marker}`);

  const openIndex = source.indexOf(openCharacter, markerIndex + marker.length);
  if (openIndex === -1) throw new Error(`Missing ${openCharacter} after ${marker}`);

  let depth = 0;
  let quote = "";
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let index = openIndex; index < source.length; index += 1) {
    const character = source[index];
    const nextCharacter = source[index + 1];

    if (lineComment) {
      if (character === "\n") lineComment = false;
      continue;
    }

    if (blockComment) {
      if (character === "*" && nextCharacter === "/") {
        blockComment = false;
        index += 1;
      }
      continue;
    }

    if (quote) {
      if (escaped) {
        escaped = false;
      } else if (character === "\\") {
        escaped = true;
      } else if (character === quote) {
        quote = "";
      }
      continue;
    }

    if (character === "/" && nextCharacter === "/") {
      lineComment = true;
      index += 1;
      continue;
    }

    if (character === "/" && nextCharacter === "*") {
      blockComment = true;
      index += 1;
      continue;
    }

    if (character === '"' || character === "'" || character === "`") {
      quote = character;
      continue;
    }

    if (character === openCharacter) depth += 1;
    if (character === closeCharacter) depth -= 1;
    if (depth === 0) return source.slice(openIndex, index + 1);
  }

  throw new Error(`Unclosed ${openCharacter}${closeCharacter} block after ${marker}`);
}

function countMatches(source, pattern) {
  return [...source.matchAll(pattern)].length;
}

function extractAssignedArray(source, marker) {
  const markerIndex = source.indexOf(marker);
  if (markerIndex === -1) throw new Error(`Missing marker: ${marker}`);

  const assignmentIndex = source.indexOf("=", markerIndex + marker.length);
  if (assignmentIndex === -1) throw new Error(`Missing assignment after ${marker}`);

  return extractDelimited(source.slice(assignmentIndex), "=", "[", "]");
}

function countArrayEntries(source, marker) {
  return countMatches(extractAssignedArray(source, marker), /^\s{2}\{/gm);
}

function countTopLevelObjectKeys(source, marker) {
  const object = extractDelimited(source, marker, "{", "}");
  return countMatches(object, /^\s{2}(?:"[^"]+"|[A-Za-z][A-Za-z0-9]*)\s*:/gm);
}

function countSessionDays(source, marker) {
  return countMatches(extractAssignedArray(source, marker), /\bday:\s*\d+/g);
}

function countPlanLabs(source, planMarker) {
  const plan = extractDelimited(source, planMarker, "{", "}");
  return countMatches(extractDelimited(plan, "labs:", "[", "]"), /\bslug:\s*"/g);
}

function escapeMarkdown(value) {
  return value.replaceAll("|", "\\|");
}

function teachingDepthLabel(subject) {
  if (subject.slug === "geography") {
    return `${subject.animationBlueprints} animation blueprints, ${subject.animationTopics} catalog topics, ${subject.labRoutes} labs`;
  }

  const parts = [`${subject.learningPackGroups} learning-pack groups`];
  if (subject.labDeckGroups) parts.push(`${subject.labDeckGroups} lab-deck groups`);
  if (subject.visualCommandGroups) parts.push(`${subject.visualCommandGroups} visual-command groups`);
  if (subject.mediaStudioGroups) parts.push(`${subject.mediaStudioGroups} media-studio groups`);
  return parts.join(", ");
}

